from pathlib import Path
import argparse,hashlib,importlib.util,json
import mpmath as mp
ROOT=Path(__file__).resolve().parents[2];SELF=Path(__file__).resolve().relative_to(ROOT).as_posix()
INPUTS='Theory/Verification/ITSM_RTAU_PHYSICAL_NORM_V1_INPUTS_2026-11-01.json'
PARENT='Analysis/MasterTests/outputs/r4c1_rtau_density_time_transport_v1_attempt_01/summary.json'
KERNEL='Analysis/MasterTests/r4c1_prepared_evolution_kernel_v2.py'
FACTORY='Analysis/MasterTests/r4c1_canonical_density_factory_v1.py'
SHA=lambda b:hashlib.sha256(b).hexdigest();ENC=lambda d:(json.dumps(d,sort_keys=True,indent=2,allow_nan=False)+'\n').encode()
def load(name,path):
 spec=importlib.util.spec_from_file_location(name,ROOT/path);m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m
def calculate():
 mp.mp.dps=100;mp.iv.dps=50;iv=mp.iv;checks=[]
 check=lambda n,p,v=None:checks.append(dict(name=n,passed=bool(p),value=v))
 pins=dict(json.loads((ROOT/INPUTS).read_text())['source_sha256']);snap={}
 for rel in (SELF,INPUTS,PARENT,KERNEL,FACTORY,'Analysis/MasterTests/r4c1_density_time_transport_v2.py','Analysis/MasterTests/r4c1_prepared_evolution_kernel_v1.py','Analysis/MasterTests/test_01_r4c1_rtau_evolution_kernel_v1.py','Analysis/MasterTests/outputs/r4c1_rtau_evolution_kernel_v1_attempt_01/failure.json','Theory/Gates/RES-001/RES001_R4C1_RTAU_EVOLUTION_KERNEL_V2_SPEC_2026-11-01.md'):pins[rel]=SHA((ROOT/rel).read_bytes())
 for rel,h in pins.items():
  p=ROOT/rel;sc=Path(str(p)+'.sha256');assert SHA(p.read_bytes())==h and sc.read_text().split()[0].lower()==h
  for f in (p,sc):snap[f]=(SHA(f.read_bytes()),f.stat().st_mtime_ns)
 ctx=load('kernel_point_factory',FACTORY).point('0.3');J=ctx['J'];zero=lambda n:[J(0) for _ in range(n)]
 ab=lambda x:max(abs(mp.mpf(t)) for t in x._mpi_)
 dq=[J(coefficients=[iv.mpf(i+1)/101,(-1)**i*iv.mpf(i+2)/103,-iv.mpf(i+1)/202]) for i in range(13)]
 dd=[J(coefficients=[t.c[1],2*t.c[2],-t.c[1]/2]) for t in dq]
 dp=[J(coefficients=[(-1)**i*iv.mpf(i+1)/107,iv.mpf(i+3)/109,iv.mpf(i+1)/211]) for i in range(13)]
 w=[J(coefficients=[iv.mpf(i+1)/113,-iv.mpf(i+2)/127,iv.mpf(i+1)/226]) for i in range(3)]
 wz=[J(coefficients=[t.c[1],2*t.c[2],iv.mpf(0)]) for t in w]
 th=J.variable(iv.mpf('.3'));psi4=((ctx['j'].trig(th,True)/29+16*ctx['j'].trig(2*th,True)/31)*(iv.mpf(1)/1000)).c[0]
 kernel=load('prepared_composed_kernel',KERNEL);result=kernel.apply(ctx,dq,dd,dp,psi4,iv.mpf(1)/17,w,wz)
 frozen=json.loads((ROOT/PARENT).read_text())['point_controls'][0]
 interval=lambda pair:iv.mpf([mp.mpf(tuple(t)) for t in pair])
 # The expected numbers are the earlier independent raw-density/current
 # Ward comparison, not values generated by this adapter.
 check('composed_background_density_current_retains_frozen_defect',ab(result['background_clock_residual']-interval(frozen['direct_clock_residual']))<mp.mpf('1e-28'))
 check('composed_all_field_tangent_retains_frozen_Ward_defect',ab(result['delta_clock_residual']-interval(frozen['direct_tangent_residual']))<mp.mpf('1e-28'))
 check('composed_auxiliary_secondary_closed',ab(result['auxiliary_secondary_tangent'])<mp.mpf('1e-28'))
 check('composed_background_auxiliary_spatial_jets',max(ab(x) for x in result['auxiliary_background_mismatch'])<mp.mpf('1e-28'))
 # A pure coordinate shift must act on every canonical field and momentum,
 # including its density Jacobian, rather than just correcting the metric.
 shifted=kernel.apply(ctx,zero(13),zero(13),zero(13),psi4,iv.mpf(0),w,wz)
 gauge=load('kernel_canonical_dual','Analysis/MasterTests/r4c1_gauge_velocity_v1.py')
 field=gauge.lie_fields(ctx['q'],ctx['d'],w,wz)
 pz=[J(coefficients=[t.c[1],2*t.c[2],iv.mpf(0)]) for t in ctx['pi']]
 momentum=gauge.lie_momenta(ctx['pi'],pz,w,wz)
 check('composed_shift_all_canonical_field_jets',max(ab((x-y).c[k]) for x,y in zip(shifted['field_rate_nonaux'],field[:13]) for k in range(3))<mp.mpf('1e-28'))
 check('composed_shift_all_canonical_momentum_densities',max(ab(x-y.c[0]) for x,y in zip(shifted['momentum_rate'],momentum))<mp.mpf('1e-28'))
 check('composed_shift_density_advection',ab(shifted['density_rate']-(shifted['density']*w[2]).c[1])<mp.mpf('1e-28'))
 origin=kernel.apply(ctx,zero(13),zero(13),zero(13),psi4,iv.mpf(0),zero(3),zero(3))
 check('zero_direction_all_composed_rates_vanish',max([ab(t.c[k]) for t in origin['field_rate_nonaux'] for k in range(3)]+[ab(t) for t in origin['momentum_rate']]+[ab(origin['density_rate']),ab(origin['direct_density_rate']),ab(origin['auxiliary_rate_value'])])<mp.mpf('1e-28'))
 check('no_unsupported_auxiliary_or_scalar_rate_jets_exposed',result['auxiliary_time_spatial_rates']==result['scalar_momentum_time_spatial_rates']=='NOT_RETURNED')
 for f,(h,t) in snap.items():assert SHA(f.read_bytes())==h and f.stat().st_mtime_ns==t
 check('all_source_bytes_and_mtimes_preserved',True,len(snap))
 return dict(kind='R4C1_RTAU_EVOLUTION_KERNEL_V2',passed=sum(x['passed'] for x in checks),total=len(checks),checks=checks,source_sha256=pins,
  scope='single-point integration of previously derived canonical/auxiliary/current/density rows with caller-supplied shift; no new physical norm derivation',
  global_compatible_periodic_composition='INCOMPLETE',physical_norm='NOT_DERIVED',controlled_time_evolution=False,review='DEFERRED',physics_pass=False,gate_effect='NONE',G1_G6='INCOMPLETE')
def main():
 ap=argparse.ArgumentParser();g=ap.add_mutually_exclusive_group(required=True);g.add_argument('--output-dir',type=Path);g.add_argument('--replay',type=Path);a=ap.parse_args();d=calculate();data=ENC(d)
 if a.replay:assert a.replay.read_bytes()==data;print('READ_ONLY_REPLAY_EXACT',SHA(data))
 else:
  a.output_dir.mkdir(parents=True,exist_ok=False);p=a.output_dir/'summary.json';p.write_bytes(data);Path(str(p)+'.sha256').write_text(SHA(data)+'\n');print(json.dumps(dict(passed=d['passed'],total=d['total'],receipt=str(p))))
 return 0 if d['passed']==d['total'] else 1
if __name__=='__main__':raise SystemExit(main())
